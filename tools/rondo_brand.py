#!/usr/bin/env python3
"""Generates Rondo's mark: the launcher icon, its colour presets, the
themed (monochrome) layer and the splash animation.

The mark is a record with a scalloped edge and a play triangle at its
centre, sitting on a larger copy of itself turned half a lobe: the theme
and its return, which is what a rondo is. Every drawable below is written
by this file. Change the geometry or a colour here and run it again;
do not edit the XML by hand.

    python3 tools/rondo_brand.py            # writes app/src/main/res/drawable
    python3 tools/rondo_brand.py --preview  # also writes docs/brand/rondo-icon.svg
"""
import math
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
RES = ROOT / "app/src/main/res/drawable"

# Adaptive icon canvas: 108 units, of which the centre 66 is always shown.
SIZE = 108
C = SIZE / 2
LOBES = 12
DISC_RADIUS, ECHO_RADIUS, DEPTH = 23.5, 29.5, 0.052
PLAY_RADIUS, PLAY_CORNER = 10.6, 2.7


def n(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def pt(p):
    return f"{n(p[0])},{n(p[1])}"


def scallop(radius, phase_deg=0.0):
    """r(t) = radius * (1 + DEPTH * cos(LOBES * t)), as cubic Beziers.

    Four segments per lobe, each built from the curve's exact tangents,
    which is within a hundredth of a unit of the true curve.
    """
    phase = math.radians(phase_deg)
    count = LOBES * 4
    step = 2 * math.pi / count

    def r(t):
        return radius * (1 + DEPTH * math.cos(LOBES * (t - phase)))

    def point(t):
        return (C + r(t) * math.cos(t), C + r(t) * math.sin(t))

    def tangent(t):
        dr = -radius * DEPTH * LOBES * math.sin(LOBES * (t - phase))
        return (dr * math.cos(t) - r(t) * math.sin(t), dr * math.sin(t) + r(t) * math.cos(t))

    out = ["M" + pt(point(0))]
    for i in range(count):
        t0, t1 = i * step, (i + 1) * step
        p0, p1, d0, d1 = point(t0), point(t1), tangent(t0), tangent(t1)
        c0 = (p0[0] + d0[0] * step / 3, p0[1] + d0[1] * step / 3)
        c1 = (p1[0] - d1[0] * step / 3, p1[1] - d1[1] * step / 3)
        out.append(f"C{pt(c0)} {pt(c1)} {pt(p1)}")
    return "".join(out) + "Z"


def play():
    """A rounded triangle pointing right, nudged right so it looks centred."""
    cx = C + PLAY_RADIUS * 0.07
    verts = [
        (cx + PLAY_RADIUS * math.cos(a), C + PLAY_RADIUS * math.sin(a))
        for a in (0, 2 * math.pi / 3, 4 * math.pi / 3)
    ]
    reach = PLAY_CORNER * math.sqrt(3)  # corner radius / tan(30 degrees)

    def toward(a, b):
        length = math.hypot(b[0] - a[0], b[1] - a[1])
        return (a[0] + (b[0] - a[0]) / length * reach, a[1] + (b[1] - a[1]) / length * reach)

    out = []
    for i, v in enumerate(verts):
        enter, leave = toward(v, verts[i - 1]), toward(v, verts[(i + 1) % 3])
        out.append(("M" if i == 0 else "L") + pt(enter))
        out.append(f"A{n(PLAY_CORNER)},{n(PLAY_CORNER)} 0 0 1 {pt(leave)}")
    return "".join(out) + "Z"


ECHO = scallop(ECHO_RADIUS, phase_deg=180 / LOBES)
DISC = scallop(DISC_RADIUS)
PLAY = play()

# name -> (background, echo, disc, play). The default is Rondo's own; the
# others recolour the same mark for the icon presets in Settings.
VARIANTS = {
    "": ("#4B3BEB", "#3626C9", "#FFF1E0", "#FF6B3D"),
    "_crimson": ("#1F0606", "#7F0000", "#FFEBEE", "#C62828"),
    "_midnight": ("#0B0C10", "#1E1F2B", "#00E5FF", "#0B0C10"),
    "_emerald": ("#051A08", "#0E3811", "#E8F5E9", "#1B5E20"),
    "_sunset": ("#260D00", "#9C3700", "#FFF3E0", "#E65100"),
    "_ocean": ("#041630", "#072B64", "#E1F5FE", "#0D47A1"),
    "_blossom": ("#190E2E", "#512DA8", "#F3E5F5", "#7E57C2"),
    "_monochrome": ("#0D0D0D", "#212121", "#FFFFFF", "#0D0D0D"),
    "_solar": ("#241200", "#A0520D", "#FFFDE7", "#F57F17"),
}

HEAD = (
    '<?xml version="1.0" encoding="utf-8"?>\n'
    "<!-- Generated by tools/rondo_brand.py. Do not edit by hand. -->\n"
)
VECTOR = (
    '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
    '    android:width="108dp"\n    android:height="108dp"\n'
    '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
)


def path(data, color, extra=""):
    return f'    <path\n        android:fillColor="{color}"{extra}\n        android:pathData="{data}" />\n'


def write(name, body):
    (RES / name).write_text(HEAD + body, encoding="utf-8")


def launcher():
    for suffix, (bg, echo, disc, tri) in VARIANTS.items():
        write(
            f"ic_launcher_background{suffix}.xml",
            VECTOR + path("M0,0h108v108h-108z", bg) + "</vector>\n",
        )
        write(
            f"ic_launcher_foreground{suffix}.xml",
            VECTOR + path(ECHO, echo) + path(DISC, disc) + path(PLAY, tri) + "</vector>\n",
        )
    # Themed icons keep only the alpha, so the triangle is a hole and the
    # echo is the same ink at a third of its strength.
    write(
        "ic_launcher_monochrome.xml",
        VECTOR
        + path(ECHO, "#000000", '\n        android:fillAlpha="0.34"')
        + path(DISC + PLAY, "#000000", '\n        android:fillType="evenOdd"')
        + "</vector>\n",
    )


def splash():
    """The mark assembling itself: echo, then the record, then the triangle."""
    _, _, disc, tri = VARIANTS[""]
    echo = "#5B4BFF"  # one step brighter than the icon's, for a dark ground

    def group(name, data, color, rotation):
        return (
            f'            <group\n                android:name="{name}"\n'
            f'                android:pivotX="54"\n                android:pivotY="54"\n'
            f'                android:rotation="{rotation}"\n'
            f'                android:scaleX="0"\n                android:scaleY="0">\n'
            f'                <path\n                    android:fillColor="{color}"\n'
            f'                    android:pathData="{data}" />\n            </group>\n'
        )

    def anim(prop, start, duration, a, b, curve):
        return (
            f'                <objectAnimator\n                    android:propertyName="{prop}"\n'
            f'                    android:startOffset="{start}"\n                    android:duration="{duration}"\n'
            f'                    android:valueFrom="{a}"\n                    android:valueTo="{b}"\n'
            f'                    android:valueType="floatType"\n'
            f'                    android:interpolator="{curve}" />\n'
        )

    pop = "@android:anim/overshoot_interpolator"
    ease = "@android:interpolator/fast_out_slow_in"

    def target(name, start, rotation):
        body = anim("scaleX", start, 420, 0, 1, pop) + anim("scaleY", start, 420, 0, 1, pop)
        if rotation:
            body += anim("rotation", start, 620, rotation, 0, ease)
        return (
            f'    <target android:name="{name}">\n        <aapt:attr name="android:animation">\n'
            f"            <set>\n{body}            </set>\n        </aapt:attr>\n    </target>\n"
        )

    write(
        "avd_splash.xml",
        '<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    xmlns:aapt="http://schemas.android.com/aapt">\n'
        '    <aapt:attr name="android:drawable">\n'
        '        <vector\n            android:width="108dp"\n            android:height="108dp"\n'
        '            android:viewportWidth="108"\n            android:viewportHeight="108">\n'
        + group("echo", ECHO, echo, -45)
        + group("disc", DISC, disc, 45)
        + group("play", PLAY, tri, 0)
        + "        </vector>\n    </aapt:attr>\n"
        + target("echo", 0, -45)
        + target("disc", 90, 45)
        + target("play", 280, 0)
        + "</animated-vector>\n",
    )


def preview():
    """A contact sheet for looking at the icon: masks, themed, presets."""
    cells = []
    x = 0

    def cell(bg, layers, mask, label):
        nonlocal x
        clip = f"clip{len(cells)}"
        shape = (
            f'<circle cx="54" cy="54" r="36"/>' if mask == "circle"
            else '<rect x="18" y="18" width="72" height="72" rx="20"/>'
        )
        body = f'<rect width="108" height="108" fill="{bg}"/>' + "".join(
            f'<path d="{d}" fill="{c}" fill-rule="evenodd" fill-opacity="{o}"/>' for d, c, o in layers
        )
        cells.append(
            f'<g transform="translate({x},0)"><clipPath id="{clip}">{shape}</clipPath>'
            f'<g clip-path="url(#{clip})">{body}</g>'
            f'<text x="54" y="104" font-size="6" text-anchor="middle" fill="#888">{label}</text></g>'
        )
        x += 84

    for suffix, (bg, echo, disc, tri) in VARIANTS.items():
        cell(bg, [(ECHO, echo, 1), (DISC, disc, 1), (PLAY, tri, 1)],
             "circle" if suffix == "" else "squircle", suffix.strip("_") or "rondo")
    bg, echo, disc, tri = VARIANTS[""]
    cell(bg, [(ECHO, echo, 1), (DISC, disc, 1), (PLAY, tri, 1)], "squircle", "rondo")
    cell("#DCE4D8", [(ECHO, "#28331F", 0.34), (DISC + PLAY, "#28331F", 1)], "circle", "themed")
    out = ROOT / "docs/brand"
    out.mkdir(parents=True, exist_ok=True)
    (out / "rondo-mark.svg").write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72">'
        f'<rect x="18" y="18" width="72" height="72" rx="20" fill="{bg}"/>'
        f'<path d="{ECHO}" fill="{echo}"/><path d="{DISC}" fill="{disc}"/>'
        f'<path d="{PLAY}" fill="{tri}"/></svg>\n',
        encoding="utf-8",
    )
    (out / "rondo-icon.svg").write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {x + 24} 108" '
        f'font-family="sans-serif">{"".join(cells)}</svg>\n',
        encoding="utf-8",
    )


if __name__ == "__main__":
    launcher()
    splash()
    if "--preview" in sys.argv:
        preview()
    print(f"wrote {len(VARIANTS) * 2 + 2} drawables")
